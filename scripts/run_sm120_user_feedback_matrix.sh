    LONG_CONTEXT_MIXED_ARRIVAL_CASE_SPECS="${LONG_CONTEXT_MIXED_ARRIVAL_CASE_SPECS:-decode_then_59k:1900:1900:after_first_token:0:256:128,decode_then_124k:4000:4000:after_first_token:0:256:128,long_then_short:4000:192:fixed_delay:2:128:64}" \
    LONG_CONTEXT_MIXED_ARRIVAL_REPEAT_COUNT="${LONG_CONTEXT_MIXED_ARRIVAL_REPEAT_COUNT:-3}" \
