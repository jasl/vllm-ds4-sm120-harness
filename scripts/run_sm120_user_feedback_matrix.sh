mkdir -p "${USER_FEEDBACK_MATRIX_ROOT}"

failures=0
run_child() {
  local child_out="$1"
  shift

  mkdir -p "${child_out}"
  set +e
  "$@" >"${child_out}/child.stdout.log" 2>"${child_out}/child.stderr.log"
  local code="$?"
  set -e
  if [[ "${code}" != "0" ]]; then
    failures=1
  fi
}

