    PREFIX_CACHE_STRESS_MAX_TOKENS="${PREFIX_CACHE_STRESS_MAX_TOKENS:-256}" \
    "${SCRIPT_DIR}/run_sm120_mtp1_prefix_cache_diagnostics.sh"
